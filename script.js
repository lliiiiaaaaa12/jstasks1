// 8-тапсырма. Дүкендегі жеңілдік
// ========================================

{
    let price = 25000;
    let discount = 0;

    console.log("\n8-тапсырма. Дүкендегі жеңілдік");

    if (price >= 20000) {
        discount = price * 0.10;
    }

    let finalPrice = price - discount;

    console.log("Бастапқы баға: " + price + " ₸");
    console.log("Жеңілдік: " + discount + " ₸");
    console.log("Соңғы сома: " + finalPrice + " ₸");
}


